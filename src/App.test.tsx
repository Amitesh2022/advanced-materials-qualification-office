// @vitest-environment jsdom
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { render, screen } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import App from './App'

describe('advanced materials qualification office', () => {
  it('loads qualification files from the Java API', async () => {
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue({
      ok: true,
      json: async () => [{ id: 1, title: 'Graphene thermal interface qualification', owner: 'Leuven Materials Validation Team', status: 'Review', priority: 'High' }],
    }))
    const client = new QueryClient({ defaultOptions: { queries: { retry: false } } })
    render(<QueryClientProvider client={client}><App /></QueryClientProvider>)
    expect(await screen.findByText('Graphene thermal interface qualification')).toBeTruthy()
    expect(screen.getByRole('heading', { name: 'Advanced Materials Qualification Office' })).toBeTruthy()
  })
})
